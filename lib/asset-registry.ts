export function resolveAsset(path: string): string {
  if (!path) return ""
  let cleanPath = path.startsWith("/") ? path.slice(1) : path
  if (cleanPath.startsWith("assets/")) {
    cleanPath = cleanPath.slice("assets/".length)
  }
  if (ASSET_MAP[cleanPath]) return ASSET_MAP[cleanPath]
  if (path.startsWith("http://") || path.startsWith("https://") || path.startsWith("data:")) {
    return path
  }
  const baseName = cleanPath.replace(/\.(png|jpe?g)$/i, ".webp")
  if (ASSET_MAP[baseName]) return ASSET_MAP[baseName]
  return `${GITHUB_RELEASE_V2_BASE}/${baseName}`
}
